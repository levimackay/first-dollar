import { readdir, writeFile } from 'node:fs/promises';
const dir = new URL('../src/lint/rules/', import.meta.url);
const names = (await readdir(dir)).filter((n) => n.endsWith('.mjs') && n !== 'index.mjs').sort();
const ident = (n) => n.replace('.mjs', '').replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const body = names.map((n) => `import ${ident(n)} from './${n}';`).join('\n')
  + `\n\nexport default [${names.map(ident).join(', ')}];\n`;
await writeFile(new URL('index.mjs', dir), `// Generated by scripts/gen-rule-index.mjs. Do not edit.\n${body}`);
console.log(`rules: ${names.length}`);
